// Generates public/sw.js with a per-build cache version so every deployment replaces old caches.
import { writeFileSync } from "node:fs";
import { execSync } from "node:child_process";

let version = process.env.VERCEL_GIT_COMMIT_SHA || "";
if (!version) {
  try { version = execSync("git rev-parse --short HEAD", { stdio: ["ignore", "pipe", "ignore"] }).toString().trim(); } catch {}
}
version = (version || "dev").slice(0, 12) + "-" + Date.now().toString(36);

const sw = `/* Yordan Decorations & Building – service worker. Generated by scripts/generate-sw.mjs. */
const VERSION = ${JSON.stringify(version)};
const PRECACHE = "yordan-precache-" + VERSION;
const PAGES = "yordan-pages-" + VERSION;
const STATIC = "yordan-static-" + VERSION;
const MEDIA = "yordan-media-" + VERSION;
const ALL = [PRECACHE, PAGES, STATIC, MEDIA];

const OFFLINE_URL = "/offline";
const PRECACHE_URLS = [OFFLINE_URL, "/images/logo.webp", "/icons/icon-192.png", "/icons/icon-512.png", "/legal.css"];
const MAX_PAGES = 20, MAX_MEDIA = 80;

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(PRECACHE).then((c) => c.addAll(PRECACHE_URLS)).then(() => self.skipWaiting())
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith("yordan-") && !ALL.includes(k)).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener("message", (e) => { if (e.data === "SKIP_WAITING") self.skipWaiting(); });

async function trim(name, max) {
  const cache = await caches.open(name);
  const keys = await cache.keys();
  if (keys.length > max) await Promise.all(keys.slice(0, keys.length - max).map((k) => cache.delete(k)));
}

async function networkFirstPage(request) {
  try {
    const res = await fetch(request);
    // Only cache successful, public page responses.
    if (res.ok && res.type === "basic") {
      const cache = await caches.open(PAGES);
      cache.put(request, res.clone()).then(() => trim(PAGES, MAX_PAGES));
    }
    return res;
  } catch {
    const cached = await caches.match(request, { ignoreSearch: true });
    return cached || (await caches.match(OFFLINE_URL)) || Response.error();
  }
}

async function cacheFirst(request, name) {
  const cached = await caches.match(request);
  if (cached) return cached;
  const res = await fetch(request);
  if (res.ok) (await caches.open(name)).put(request, res.clone());
  return res;
}

async function staleWhileRevalidate(request, name, max) {
  const cache = await caches.open(name);
  const cached = await cache.match(request);
  const network = fetch(request)
    .then((res) => { if (res.ok) { cache.put(request, res.clone()).then(() => trim(name, max)); } return res; })
    .catch(() => cached);
  return cached || network;
}

self.addEventListener("fetch", (event) => {
  const { request } = event;
  // Never touch non-GET (e.g. the quote form POST), cross-origin requests (FormSubmit, Google Fonts, WhatsApp) or APIs.
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  if (url.pathname.startsWith("/api/") || url.pathname === "/sw.js") return;

  if (request.mode === "navigate") {
    event.respondWith(networkFirstPage(request));
  } else if (url.pathname.startsWith("/_next/static/")) {
    event.respondWith(cacheFirst(request, STATIC)); // content-hashed, immutable
  } else if (url.pathname.startsWith("/images/") || url.pathname.startsWith("/icons/") || url.pathname.startsWith("/splash/")) {
    event.respondWith(staleWhileRevalidate(request, MEDIA, MAX_MEDIA));
  } else if (url.pathname === "/legal.css" || url.pathname === "/manifest.webmanifest") {
    event.respondWith(staleWhileRevalidate(request, STATIC, 200));
  }
});
`;
writeFileSync(new URL("../public/sw.js", import.meta.url), sw);
console.log("Generated public/sw.js, cache version", version);
